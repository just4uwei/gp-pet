--
-- 迁移只前进不回退。改这里等于改已发布用户的库 —— 一律新增 015_xxx.sql，不要编辑本文件。
--
-- ## 为什么需要它：这是唯一一个「今天不做就永久少一天」的数据缺口
--
-- 数据源（东财 `f127`）给的是**当前**行业名。拿它回标历史是**未来函数** ——
-- 「按 2020 年的行业中性化」需要知道 2020 年**当时**它属于哪个行业，而不是今天的。
-- 聚宽的 `get_history_industry` 是唯一直接给纳入/剔除历史的源，但它的协议
-- （5.1/3.2/4.1）禁止把数据或加工物提供给第三方或商业使用 ⇒ **不能入库分发**
-- （见 docs/notes/信源台账.md §7）。
--
-- ⇒ 我们只能**从今天起一天天攒**。其余数据缺口什么时候补都能补齐，这一个补不回来。
--
-- ## 为什么不是 `watchlist.industry` 那一列
--
-- 那一列存的是**当前值**，被 `INSERT … ON CONFLICT … COALESCE` 覆盖式更新。
-- 行业调整（并购、主营变更、交易所重新归类）发生时旧值直接消失，
-- 而「什么时候变的」恰恰是这张表存在的全部理由。两者都留：
-- 那一列答「现在是什么」（面板要用），这张表答「那天是什么」。
--
-- ## 一行一次**变化**，不是一行一天
--
-- 79 只 × 一年 ≈ 2 万行，而其中 99.9% 会是同一个行业名重复。
-- 只在与上一行不同时才写 ⇒ 这张表实际是一份**变更日志**。
-- 查「code 在 D 日属于哪个行业」= 取 `observed_date <= D` 里最新的那一行。
--
-- ⚠ 代价要知道：**第一次观测到的那天不等于「它那天才变成这个行业」**。
-- 首行的 `observed_date` 只是「我们开始记的那天」，在它之前一律 unknown ——
-- 不许把首行往前外推，那正是这张表要防的未来函数。`note` 列记这件事。
--
-- ## ⚠ 观测频率是**每周**，不是每天（2026-08-23 实测纠正）
--
-- 它挂在 `refreshProfiles()` 上，而那个挂在休市维护里、
-- 由 `MAINTENANCE_INTERVAL_MS = 7 天` 门着 ⇒ **一周最多一次观测**。
-- 「逐日留痕」那个说法是错的，写的时候没查那个常量。
--
-- **这不影响它的用途**：行业调整（并购、主营变更、交易所重新归类）是**季度级**的事件，
-- 一周的分辨率绰绰有余；而 `observed_date` 本来就只是「我们看到的那天」而不是生效日
-- （见上面那条边界）⇒ 周频与日频在这张表的语义里没有差别。
--
-- **不要为了它去调小 `MAINTENANCE_INTERVAL_MS`** —— 那个常量同时门着日历刷新、
-- 裁剪与备份，为一个季度级的字段把它们全部提频是错误的代价分配。
--
-- ## 不进裁剪
--
-- 与 `shadow_*` / `ai_explain` / `trade_log` 同一档：**无法重建**。
-- 删掉就等于把攒过的日子扔了，而它们买不回来。`pruneAll` 不碰这张表。

CREATE TABLE IF NOT EXISTS industry_history (
  code          TEXT NOT NULL,
  -- 观测日（北京时区的自然日 YYYY-MM-DD）。不是「行业变更生效日」——
  -- 我们只知道自己看到的那天，见头注释里那条边界
  observed_date TEXT NOT NULL,
  industry      TEXT NOT NULL,
  -- 'FIRST' = 这只票的第一条观测（之前一律 unknown，不许外推）
  -- 'CHANGE' = 与上一条不同
  note          TEXT NOT NULL,
  PRIMARY KEY (code, observed_date)
);

-- 「某只票的最近一条」是最频繁的查询（每次刷新都要拿它来比对是否变化）
CREATE INDEX IF NOT EXISTS idx_industry_history_code_date
  ON industry_history (code, observed_date DESC);
