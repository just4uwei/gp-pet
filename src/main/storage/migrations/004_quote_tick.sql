--
-- 迁移只前进不回退。改这里等于改已发布用户的库 —— 一律新增 005_xxx.sql，不要编辑本文件。
--
-- ## 这张表是什么
--
-- 盘中每轮 tick（30s）已经在拉快照（engine/tick.ts 的 refreshSnapshots），
-- 这里只是把那份**本来就拿到了**的最新价顺手落一行。所以它**不新增任何网络请求**、
-- 不碰限流器、不影响 provider 健康度 —— 这一点是它能存在的前提：
-- 为了画一张图去多发一轮请求，违反 docs/03 §2.4 的请求礼节。
--
-- ## 以及**它不是什么**
--
--   * **不是 K 线的替代品。** 回测、指标、信号判定一律只读 kline_daily，
--     一个字都不读这张表。它纯粹是展示层的素材。
--   * **不参与任何信号判定。** 引擎不认识它。
--   * **不是完整的分时。** 覆盖范围 = 应用开着的时段。用户下午一点才开机，
--     上午就是空的。渲染层必须把这个洞画出来（相邻点超过 5 分钟就断线，
--     并标注「分时自 xx:xx 起在本机记录」），**不许用直线连过去** ——
--     那条斜线看着像分时线，但那段时间里什么都没被观测到。
--   * **不存 stale 快照。** 取数失败时上层会重放缓存值，那些点不写进来 ——
--     写了会画出一条「其实没有成交」的平线，正是 docs/03「绝不假装实时」要防的。
--
-- ## 不设外键
--
-- 不加指向 signal(id) 或 watchlist(code) 的外键：这张表按 7 天滚动裁剪
-- （retention.ts），而 signal 留 2 年、watchlist 是用户数据。挂上去只会让
-- 删除顺序多一处要小心的地方，而它换不来任何完整性保证 —— 一条孤儿分时点
-- 的后果只是图上多一个点。

CREATE TABLE quote_tick (
  code      TEXT NOT NULL,
  ts        INTEGER NOT NULL,   -- 墙上时刻（ms）
  last      REAL NOT NULL,
  -- 昨收，画基准线用。数据源没给时为 NULL —— **不要填 0**（约束 4：
  -- 未定义值填 0 会让基准线跑到坐标轴底下，把整张图的纵轴压扁）
  pre_close REAL,
  -- 主键即幂等闸门：盘后还会跑好几轮 tick，快照时刻不变时重复写只会被 IGNORE。
  -- 少了它，同一时刻会攒出好几行，而「点多了」这件事在折线图上完全看不出来
  -- （与 shadow_equity.trade_date 是同一条纪律）
  PRIMARY KEY (code, ts)
) WITHOUT ROWID;

-- 裁剪按时间扫全表，不带 code
CREATE INDEX idx_quote_tick_ts ON quote_tick(ts);
