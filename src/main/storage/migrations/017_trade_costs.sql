-- 017_trade_costs · 账本三件事：建仓价含不含费 · 现金分红 · 送股/转增
--
-- 迁移只前进不回退。改这里等于改已发布用户的库 —— 一律新增 018_xxx.sql，不要编辑本文件。
--
-- ## 为什么要动这张表
--
-- 007 里有三个写死的假设，逐条都会让账本给出一个**错的数而不报警**：
--
-- 1. **建仓那一笔的价被当成「已经含费的摊薄成本」，没有第二种可能。**
--    那对迁移与配置导入是对的（它们取的就是 `position.cost`），但用户自己
--    补一笔「我早就持有这只票」时，他手上有的往往是**成交价**而不是摊薄成本
--    ⇒ 按含费处理会让成本系统性偏低，而止损用的正是这个数。
--    现在由 `fee_included` 说，**新录入默认「不含」**（系统按费率补算）。
-- 2. **没有分红的位置。** 持仓成本与展示价都是**不复权**口径（docs/03 §2.3）
--    ⇒ 除权那天价格自己掉下来，成本一动不动 ⇒ 界面显示一段**假浮亏**，
--    而止损缓冲被凭空吃掉。
-- 3. **没有送转的位置。** 10 送 10 之后股数该翻倍、成本该减半，而账本一无所知
--    ⇒ 持仓股数少一半、`position.peak_price` 停在除权前
--    ⇒ 移动止损立刻读出一个**假回撤**（那个失效形状与 009 头注释里
--    `acceptLoss` 不重设 peak 的那个一模一样）。
--
-- ## 新增的列
--
-- `fee_included`（仅对 `OPENING` 有意义）：录入的 `price` 已经含手续费了吗。
--   * 0 = 不含 ⇒ 系统按费率补算一笔并摊进成本（**新录入的默认**）；
--   * 1 = 已含 ⇒ 那个价直接就是摊薄成本，不再收费；
--   * **NULL = 老行** ⇒ 按 1 处理。这不是猜：007 迁移与配置导入都是从
--     `position.cost` 复制过来的，那个数**按定义**就是含费的摊薄成本。
--     ⚠ 反过来把 NULL 当 0，升级那一刻全库的期初成本会被凭空补一笔费用。
--
-- 手续费本身**不在这张表里给用户改**（2026-09-03 拍板）：它一律由费率算，
-- 而费率住 `settings.json` 的 `tradeCosts`，**唯一的写入路径是「校正成本」**
-- —— 用户抄下券商 App 上的摊薄成本，软件从流水反解佣金率
-- （`main/trades/fees.ts` 的 `solveCommissionRate`）。
-- 判据是可核对性：那个成本价用户每天都在看，是事实；费率不是。
--
-- ## 新增的 `side` 取值（列是 TEXT 且没有 CHECK 约束，不用改结构）
--
--   side       | price          | shares     | fee | realized        | 效果
--   -----------+----------------+------------+-----+-----------------+------------------------------
--   DIVIDEND   | 税后每股派现   | 分红股数   |  0  | 摊到 0 后的余额 | cost -= 到账额 / 持股数
--   SPLIT      | 0（真的没付钱）| **新增**股数| 0  | NULL            | 股数增、成本按比例摊薄、总成本不变
--
-- 三条容易读错的：
--
-- 1. **`SPLIT` 的 `price = 0` 不是「用假值冒充」**（对照约束 4 与 `realized` 的
--    NULL vs 0）。送股**真的没有成交价** —— 你一分钱没付，0 是事实。
--    而 `fee = 0` 同理：它不是成交，没有佣金也没有税。
--    对比「价已含费」那种建仓行的 `fee = 0` —— **那个才是「不知道」**。
-- 2. **分红走「扣减摊薄成本」，不进已实现盈亏**（2026-09-03 用户拍板）。
--    理由是上面第 2 条：除权日价格与成本同步下移 ⇒ 浮亏不变、止损线跟着下移，
--    不会凭空触发。那笔钱要等卖出时才结转进 `realized`
--    ⇒ 界面上「累计分红」与「已实现盈亏」**必须分两行**，相加会把同一笔钱数两遍。
--    **唯一的例外**是累计分红已经把成本摊到 0：多出来的那部分记进这一行的 `realized`
--    —— 丢掉等于凭空少一笔钱，让成本变负会让浮亏百分比与止损线一起失去意义。
-- 3. **这两种行都不占 T+1 的当日买入额度。** `boughtSharesSince` 仍然只数 `BUY`
--    （送股到账当日可卖），也不进「照哪条提醒做的」那套 IS 分解（016）——
--    它们不是一次决策。

-- 刻意**可空、不给 DEFAULT**：老行落 NULL 而不是落某个具体值，
-- 那样「这一行是 017 之前的」在数据里看得出来（对照 016 那四列的同一处理）。
ALTER TABLE trade_log ADD COLUMN fee_included INTEGER;
