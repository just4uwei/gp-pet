-- 009_position_stop · 用户确认接受的那一段亏损
--
-- 迁移只前进不回退。改这里等于改已发布用户的库 —— 一律新增 010_xxx.sql，不要编辑本文件。
--
-- ## 它解决什么
--
-- `STOP_LOSS` 是 L3 强制类、不可降级（docs/05 §2.3），于是一只已经跌破 8% 的票
-- 会每天提醒同一件事 —— 而用户早就知道了，并且决定扛着。反复提醒同一件已知的事
-- 与不提醒一样有害：它会让用户开始整体忽略这个软件的提醒。
--
-- 做法不是「静默这只票」，而是**让用户重新画一条线**：确认接受当前这一段亏损，
-- 同时把止损线顺延到「现价再往下一个止损幅」。跌破新线还是会响。
--
-- ## 三条容易读错的
--
-- 1. **`stop_floor` 是绝对价、不复权**，与 `cost` 同一口径（docs/03 §2.3）。
--    用前复权价会让除权那天凭空触发或凭空不触发，而症状是「明明没跌到就提醒我了」。
-- 2. **`stop_ack_loss` 不是冗余。** 只存 `stop_floor` 的话，日后看到「止损线 8.46」
--    反推不出「他当时是在 −8% 确认的还是 −25% 确认的」—— 而那是完全不同的两件事：
--    一个是正常的止损让路，一个是已经深套了还在加码扛。这一列让那句话能被回答。
-- 3. **加仓与清仓必须把这三列清空**（落点在 trades/ledger.ts 的重建路径与 position:set）。
--    买入会改摊薄成本，旧的那条线与新成本不再是同一个判断；清仓后留着它，
--    下次建仓会莫名其妙地不提醒 —— 而「少发的错误用户发现不了」。
--
-- ## 它只作用于固定止损，也只作用于本机
--
-- 移动止损 / 回撤减仓 / 盈利保护照旧响：用户接受的是「这一段下跌」，
-- 不是「所有风控都别响了」。
--
-- 而且它**绝不进回测与影子运行**：那是用户对某一次具体持仓的决定，不是策略的一部分。
-- 让它影响 src/backtest 或 main/shadow 会把「我扛住了没卖」记成策略绩效
-- （`Position.stopFloor` 是可选字段，那两处不设它，天然不受影响 —— 别去「补上」）。

ALTER TABLE position ADD COLUMN stop_floor REAL;
ALTER TABLE position ADD COLUMN stop_ack_at INTEGER;
ALTER TABLE position ADD COLUMN stop_ack_loss REAL;
