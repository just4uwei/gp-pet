-- 迁移只前进不回退。改这里等于改已发布用户的库 —— 一律新增 006_xxx.sql，不要编辑本文件。
--
-- ## 为什么要加这两列
--
-- 在这之前 watch_point 只有触发条件（metric/op/threshold）和一句 note。
-- 三个月后回看，「我为什么设了这个」答得上（note 里是那段解读的摘录），
-- 但「当时判的是涨还是跌、后来兑现没有」答不上 —— 而后者才是这张表真正的价值：
-- 一条到期未命中的 INVALIDATE 观察点，只有配上「当时判的是上涨」才构成一个结论。
--
-- ## 为什么是**两**列而不是一列
--
--   verdict       归一化枚举，用来上色与按方向归类
--   verdict_text  未加工的判断原文，用来回答「当时到底是怎么说的」
--
-- 只存枚举会把模型说的那句话丢掉（枚举是有损压缩）；只存原文则列表里没法按方向归类。
-- 两列各有各的用途，合成一列必然牺牲其中一个。
--
-- ## verdict 允许为 NULL，而且那不是错误
--
-- 归一化走白名单，认不出就留空 —— 与 watch/suggestion.ts 开头那条
-- 「抽错一个数比抽不到糟得多」是同一条纪律：把「继续震荡上行」硬归成 UP，
-- 会让用户在列表上看到一个他从没确认过的方向。留空时 verdict_text 照存，
-- 信息不丢，只是没法归类。
--
-- 同理这两列都是**用户确认过的**：表单里可改，改了记 USER_EDITED。
-- 模型的建议只走到预填这一步（003_watch.sql 头注释：判定不涉及模型）。

ALTER TABLE watch_point ADD COLUMN verdict TEXT;       -- UP | DOWN | RANGE，认不出为 NULL
ALTER TABLE watch_point ADD COLUMN verdict_text TEXT;  -- 判断原文，最多 40 字
